-- ── 功能2:MPP 多节点 ───────────────────────────────────────────────────
-- Doris / StarRocks 的 FE 是多副本部署,任一节点都能接受查询。单节点配置意味着
-- 那个节点挂了整个数据源就不可用 —— 而 MySQL 协议驱动原生支持多主机故障转移
-- (jdbc:mysql://h1:p1,h2:p2/db),不用它等于白白放弃了对方已经做好的高可用。
--
-- 用独立列而不是塞进 properties_json:节点列表是连接身份的一部分
-- (改了它就是连到别的集群去了),而 properties 是驱动调优参数。
-- 二者的变更语义不同 —— 改节点应当触发重新验证,改 useSSL 不必。
ALTER TABLE md_datasource ADD COLUMN nodes_json TEXT;

COMMENT ON COLUMN md_datasource.nodes_json IS
    '附加节点,JSON 数组 [{"host":"h","port":9030}]。仅 MPP 类型使用;'
    'host/port 列仍是主节点,故障转移时驱动按"主节点 + 附加节点"顺序尝试。';


-- ── 功能28:空间启用/停用 ───────────────────────────────────────────────
-- pf_workspace.status 列已存在(ACTIVE / SUSPENDED),此前只有默认值没有出口。
-- 停用是"暂时冻结"而非删除:里面的数据源、任务、审计记录都还在,
-- 只是任何人都进不去。这与删除的区别对合规审计很重要 —— 停用一个空间
-- 不该让它的历史记录跟着消失。
CREATE INDEX idx_pf_workspace_status ON pf_workspace (status) WHERE deleted = FALSE;


-- ── 功能28:空间管理员 ─────────────────────────────────────────────────
-- 不新增"管理员"字段。空间管理员 = 在该空间下被授予内置 WORKSPACE_ADMIN
-- 角色的用户 —— 复用已有的角色体系,而不是为"谁管理这个空间"再造一套
-- 平行的权限来源。两套来源必然会不一致,而不一致的表现是
-- "界面上显示他是管理员,但他点什么都是 403"。
--
-- 这里只补一个索引,支撑"列出某空间的管理员"这个查询。
CREATE INDEX idx_pf_user_role_by_role ON pf_user_role (workspace_id, role_id);
